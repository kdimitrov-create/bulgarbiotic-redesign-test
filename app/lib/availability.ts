import {stockFor} from './product-marks';

/**
 * Наличен ли е продукт/вариант според витрината.
 *
 * Съществува заради едно разминаване в Storefront API-то: то смята
 * `availableForSale` по правилото „количество > 0 ИЛИ продължи продажбите" и
 * НЕ гледа дали проследяването на количеството изобщо е включено. При изключено
 * проследяване количество няма, затова полето пада на `false`, докато самата
 * платформа продава продукта без възражение - `cartCreate` минава, а панелът
 * показва наличността като „∞" (заварено на 01.09.2026 по продукт 37).
 *
 * Разликата между двата случая е в `quantityAvailable`:
 *
 *   - `null` - проследяването е изключено, няма какво да се брои → наличен
 *   - `0`    - проследяването работи и наличността е свършила → изчерпан
 *
 * Затова проверката е за СТРОГО `null`. Липсващо поле (`undefined`) значи, че
 * заявката изобщо не го е поискала - така е в листинговите заявки, които
 * свалят вариантите - и там няма основание да се презумира наличност.
 */
export function isAvailable(
  item?: {availableForSale?: boolean | null; quantityAvailable?: number | null} | null,
): boolean {
  if (!item) return false;
  if (item.availableForSale !== false) return true;
  return item.quantityAvailable === null;
}

/**
 * Наличен ли е ПРОДУКТ (не вариант) в списък.
 *
 * `isAvailable` върши работа само когато му подадеш вариант, защото
 * `quantityAvailable` съществува единствено там - на тип `Product` в схемата
 * на Storefront API-то го няма изобщо. А листинговата заявка на клиента иска
 * само `id handle title availableForSale`, тоест в решетката всеки продукт с
 * `availableForSale: false` се рисуваше „Изчерпан" - включително продукт с
 * изключено проследяване, който платформата продава без възражение.
 *
 * Точно това се случи с „Пакет Имунитет" на 28.09.2026: собствената му
 * страница го обявяваше „В наличност" и го продаваше, а категорийният списък
 * го зачеркваше.
 *
 * Липсващото число идва от каталожната снимка (`product-marks`), която и без
 * това се дърпа на всяка листингова страница - тоест нула нови заявки.
 *
 * ⚠️ Посоката е една и е тясна: продукт минава от „Изчерпан" към „наличен"
 * САМО ако снимката изрично казва `null` (проследяване изключено). Неизвестна
 * наличност (`undefined` - снимката не е стигнала или заявката е паднала)
 * оставя предпазливото поведение, а количество `0` си остава изчерпан.
 */
export function isProductAvailable(
  product?: {availableForSale?: boolean | null; quantityAvailable?: number | null} | null,
): boolean {
  if (!product) return false;
  if (product.availableForSale !== false) return true;
  const own = (product as any).quantityAvailable;
  if (own !== undefined) return own === null;
  return stockFor(product) === null;
}
