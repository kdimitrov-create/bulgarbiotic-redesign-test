/**
 * Промо кодът на серията Longevity, показван в малък попъп на всички
 * посетители (`overlays/LongevityPromo.tsx`).
 *
 * Кодът е правило №726 в панела: 30 %, само за петте продукта на серията.
 * Дали попъпът излиза, решава панелът: спре ли се или изтече ли правилото,
 * root loader-ът престава да го изброява в `live.announcedCodes` и попъпът
 * угасва без нов deploy (виж `live-discounts.server.ts`).
 *
 * Първата версия го показваше само на хората, които не идват от реклама в
 * социалните мрежи. Клиентът се отказа от това на 29.09.2026 - сега го
 * виждат всички.
 */
export const LONGEVITY_PROMO_CODE = 'Future30';

/**
 * Кодовете, за които браузърът изобщо може да научи дали действат.
 *
 * Към клиента отива само сечението с този списък, не всички действащи кодове:
 * в магазина има десетки лични и еднократни кодове, които не са за показване.
 */
export const ANNOUNCED_CODES = [LONGEVITY_PROMO_CODE];

/**
 * Касата сравнява кодовете без значение от главни и малки букви, а панелът
 * пази изписването на търговеца („Future30"). Затова и тук.
 */
export function sameCode(a: string, b: string): boolean {
  return a.trim().toUpperCase() === b.trim().toUpperCase();
}
