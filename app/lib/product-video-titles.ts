/**
 * Заглавието на секцията с видеото, по продукт.
 *
 * Дотук заглавието беше заковано в самия компонент, тоест всички продуктови
 * страници носеха един и същ ред „Как работи пробиотикът". За търсачката това
 * е един и същ H2 на двадесет и пет адреса; клиентът поиска да е редактируем.
 *
 * Тук се пише по един ред на продукт. Продукт без свой ред остава с общото
 * заглавие - то не е грешно, просто не е негово.
 *
 * Ключът е handle-ът на продукта, същият като в `product-faqs.ts`.
 */
export const PRODUCT_VIDEO_TITLES: Record<string, string> = {
  // Пример за попълване (махни решетката и смени текста):
  // 'bactology-probiotik-za-jeni-femin': 'Как работи Bactology Femin',
};

/** Общото заглавие - ползва се, докато продуктът няма свое. */
export const DEFAULT_VIDEO_TITLE = 'Как работи пробиотикът';

export function videoTitle(handle?: string | null): string {
  return (handle && PRODUCT_VIDEO_TITLES[handle]) || DEFAULT_VIDEO_TITLE;
}
