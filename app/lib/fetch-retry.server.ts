/**
 * Едно повторение, когато магазинът каже „твърде много заявки".
 *
 * ЗАЩО. Всяка страница дърпа по десетина неща от магазина - витрина, меню,
 * етикети, оферти, продукти. Отворят ли се няколко различни страници наведнъж,
 * снопът заявки надхвърля допустимото и Storefront API-то отговаря 429. Дотук
 * това хвърляше в loader-а и посетителят виждаше 500.
 *
 * Измерено на живо (14.08): двайсет различни адреса едновременно дадоха 33 от
 * 60 отговора с код 500, а истинската грешка е
 * „StorefrontApiError: Storefront API request failed: 429 Too Many Requests".
 * Провалите бяха най-бързите отговори - 0,19 сек. срещу 0,32 при успелите -
 * защото 429 се връща веднага, без да се върши работа. Поединично същите
 * адреси минаваха 12 от 12.
 *
 * КАК. `fetch` на работника се обвива веднъж на изолат. Само при 429 се чака
 * малко и се опитва повторно - веднъж. Изчакването е с разбъркване, за да не
 * тръгнат всички заявки наново в един и същи миг и да не се получи същият сноп.
 *
 * Нарочно НЕ се повтаря при други кодове: 4xx означава, че заявката е сгрешена,
 * а 5xx на магазина си е негов проблем - повторението само би удвоило товара.
 * Нарочно е само ЕДНО повторение: целта е да се преживее миг на претоварване,
 * не да се настоява.
 *
 * Това е кръпка, не лек. Истинското решение е страницата да иска по-малко неща
 * наведнъж - виж бележката за root loader-а.
 */

/**
 * Изчакванията растат: 0,3 → 0,8 → 1,6 сек., плюс разбъркване.
 *
 * Едно повторение не стигаше - измерено на живо, магазинът връщаше 429 и на
 * втория опит, защото ограничението е за сноп, а не за отделна заявка. Три
 * опита с растящо изчакване дават на снопа време да се разреди.
 */
/* ⚠️ ПРЕРАБОТЕНО 17.08.2026, след като живият магазин повали и админ панела.
 *
 * Три повторения при 429 значат ЧЕТИРИ заявки вместо една - точно когато
 * магазинът вече казва „твърде много". Тоест лекарството хранеше болестта:
 * витрината удряше ограничението, повтаряше, удряше го пак, а през това време
 * търговецът получаваше 429 в панела.
 *
 * Сега: едно повторение, и то само ако наскоро не сме виждали 429 от този
 * произход. Види ли се, за половин минута повторенията спират напълно - 429-те
 * се връщат на извикващия, който и без това знае да живее без тези данни
 * (`soft` в root). По-добре страница без етикети, отколкото магазин без админ. */
const BACKOFF_MS = [300, 800, 1600];
const JITTER_MS = 250;
/* 🛑 Тук стоеше прекъсвач: след 429 повторенията спираха за половин минута.
 * Направи нещата ЧЕТИРИ пъти по-зле (117 от 160 страници с 500 вместо 55) и
 * ето защо: админ API-то и Storefront API-то са на ЕДИН И СЪЩ произход. Едно
 * 429 от админските извиквания гасеше повторенията и за продуктовите заявки,
 * които дотогава се оправяха точно с повторение. Мерено на живо 17.08.2026. */

declare global {
  // eslint-disable-next-line no-var
  var __bbFetchRetryInstalled: boolean | undefined;
}

export function installFetchRetry(): void {
  if (typeof globalThis.fetch !== 'function') return;
  if (globalThis.__bbFetchRetryInstalled) return;
  globalThis.__bbFetchRetryInstalled = true;

  const original = globalThis.fetch.bind(globalThis);

  globalThis.fetch = async function bbFetchWithRetry(input: any, init?: any) {
    let res = await original(input, init);

    for (const base of BACKOFF_MS) {
      if (res.status !== 429) return res;
      await new Promise((done) => setTimeout(done, base + Math.floor(Math.random() * JITTER_MS)));
      try {
        res = await original(input, init);
      } catch {
        // Мрежова грешка при повторния опит: връща се последният истински
        // отговор, за да остане поведението такова, каквото извикващият очаква.
        return res;
      }
    }
    return res;
  } as typeof fetch;
}
