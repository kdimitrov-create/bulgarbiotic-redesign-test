/**
 * „По-добре страница без парче, отколкото страница с грешка."
 *
 * Тази обвивка живееше вътре в root loader-а и пазеше само него. Оттам обаче
 * е защитен само общият скелет - меню, етикети, оферти. Loader-ът на всеки
 * отделен адрес (началната, категорията, статията) пита магазина за СВОИТЕ
 * неща със същите заявки, но БЕЗ никаква защита: един отказ на Storefront или
 * на админското API хвърля право в error boundary-то и посетителят получава
 * нашата страница „500 · Нещо се обърка".
 *
 * Мерено на живо 27.08.2026 при студен кеш: два провала за петнайсетина
 * заявки в един кратък прозорец, а минути по-късно същите адреси минаваха
 * 25 от 25. Тоест магазинът има кратки мигове на отказ, а не траен проблем -
 * точно случаят, в който резервна стойност е по-добра от грешка.
 *
 * Пази от ДВЕТЕ неща:
 *   - ОТКАЗ (429/5xx/мрежа) - връща резервната стойност;
 *   - ВИСЕНЕ - заявка без отговор не е отказ, `Promise.all` не се разрешава и
 *     SSR-ът не връща нищо. Затова има и краен срок.
 *
 * Срокът е 6 s, за да не отреже законните повторения при 429: те струват до
 * 300+800+1600 ms изчакване плюс четири обиколки, тоест около 4,4 s в
 * най-лошия случай.
 */
export const SOFT_TIMEOUT_MS = 6000;

/**
 * Прави `soft` за един loader. `degraded` се пълни с етикетите на отказалите
 * заявки - полезно е да се върне към клиента там, където има какво да покаже.
 */
export function makeSoft(scope: string, degraded: string[] = []) {
  return function soft<T>(label: string, p: Promise<T>, fallback: T): Promise<T> {
    // Просрочилата се заявка може да падне и след това; без ключалка същият
    // етикет влиза в `degraded` два пъти и се логва два пъти за едно събитие.
    let settled = false;
    const fail = (why: string) => {
      if (!settled) {
        settled = true;
        degraded.push(label);
        console.error(`[${scope}] ${label} се отказа: ${why}`);
      }
      return fallback;
    };
    let timer: ReturnType<typeof setTimeout> | undefined;
    const deadline = new Promise<T>((resolve) => {
      timer = setTimeout(() => resolve(fail(`не отговори за ${SOFT_TIMEOUT_MS} ms`)), SOFT_TIMEOUT_MS);
    });
    // Изоставената заявка може да падне по-късно; без този улов това е
    // необработен отказ, който в Workers се брои за грешка на заявката.
    p.catch(() => {});
    return Promise.race([
      p.catch((error) => fail((error as Error)?.message ?? String(error))),
      deadline,
    ]).finally(() => clearTimeout(timer));
  };
}
