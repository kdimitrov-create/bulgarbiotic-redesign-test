/**
 * Държи количката на платформата в крак с нашата, без да мести клиента.
 *
 * Има две колички: нашата (Storefront API, ключ в наша бисквитка) и тази на
 * платформата (нейна сесия). `/cart` вече е резервиран и го рисува платформата,
 * тоест клиентът вижда ВТОРАТА. Ако тя не знае за добавеното, страницата излиза
 * празна - измерено 2026-08-11.
 *
 * Мостът е `cart.checkoutUrl` - подписан адрес `/checkout/adopt/<jwt>`, който
 * казва на платформата „вземи тази количка в сесията си".
 *
 * Досега това ставаше с видимо пренасочване: всяко „Купи" изхвърляше клиента в
 * касата. Тук същото се прави тихо, с една заявка на заден план, и клиентът
 * остава на страницата.
 *
 * Две подробности, без които не работи:
 *
 *  • Адресът се пренаписва към ТЕКУЩИЯ домейн. `checkoutUrl` сочи служебния
 *    `*.cloudcart.net`; заявка натам е към друг сайт и бисквитката отпада.
 *    На насочения домейн `/checkout/*` е резервиран, значи същият път минава
 *    през платформата и бисквитката е първа страна.
 *  • `credentials: 'include'`, иначе сесийната бисквитка не се записва.
 *
 * Тихо по конструкция: всяка грешка се преглъща. Непрехвърлена количка е
 * по-малка беда от спрял бутон „Купи".
 */
export async function syncCartToPlatform(checkoutUrl: string | null | undefined) {
  if (!checkoutUrl || typeof window === 'undefined') return;
  try {
    const path = new URL(checkoutUrl, window.location.origin).pathname;
    await fetch(path, {credentials: 'include', redirect: 'follow'});
  } catch {
    /* мрежата може да откаже; количката ни остава вярна така или иначе */
  }
}

/** Съобщението, с което всеки бутон казва „добавих нещо". */
export const CART_TOAST_EVENT = 'bb:cart-added';

export function announceCartAdd(text = 'Продуктът е добавен в количката') {
  if (typeof window === 'undefined') return;
  window.dispatchEvent(new CustomEvent(CART_TOAST_EVENT, {detail: text}));
}
