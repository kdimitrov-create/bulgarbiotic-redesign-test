/**
 * Кога колелото на късмета е живо.
 *
 * Проверката е НАРОЧНО на сървъра: часовникът на посетителя не важи за нищо -
 * сгрешен с два часа браузър иначе или изключва колелото по-рано, или го
 * оставя да раздава кодове след срока. Nova върви на Cloudflare Workers, тоест
 * в UTC, затова всяка граница носи изричен часови пояс (+03:00 = София).
 *
 * Ключът е часов, а не флаг, за да може deploy-ът да мине предварително:
 * бъндълът тръгва по-рано, а колелото само пали или гасне в точния час, без
 * някой да стои на клавиатурата.
 *
 * Спира се САМО показването и раздаването на нови кодове. Вече спечелените
 * кодове остават валидни: кампаниите не се пипат. Така човек, спечелил в 12:58,
 * може да поръча и вечерта.
 *
 * История: колелото беше спряно от 19.08.2026 13:00 по искане на клиента.
 * Пуснато отново на 27.08.2026, след като всеки подарък получи собствена
 * кампания със 700 еднократни 100% кода и в бъндъла не остана нито един код.
 *
 * Спира се на 09.10.2026 в 00:00 (края на 08.10) по искане на клиента.
 *
 * За да се пусне пак: `WHEEL_END = null`.
 */
export const WHEEL_END: string | null = '2026-10-09T00:00:00+03:00';

/**
 * Кога колелото се пали. `null` = веднага (както беше досега).
 *
 * Има го по същата причина, по която има и край: пускането да не иска някой да
 * стои на клавиатурата в точния час. Deploy-ът минава предварително, а
 * колелото само тръгва. За проба преди този час: `?wheel=test` в адреса.
 */
export const WHEEL_START: string | null = null;

/** Живо ли е колелото в момента `now` (по подразбиране: сега, по сървъра). */
export function isWheelLive(now: number = Date.now()): boolean {
  if (WHEEL_START) {
    const start = Date.parse(WHEEL_START);
    if (!Number.isNaN(start) && now < start) return false;
  }
  if (!WHEEL_END) return true;
  const end = Date.parse(WHEEL_END);
  return Number.isNaN(end) ? true : now < end;
}
