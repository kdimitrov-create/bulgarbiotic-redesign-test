import {redirect} from 'react-router';
import type {Route} from './+types/subscribers.cart.$hash';

/**
 * `/subscribers/cart/<хеш>` - бутонът „Обратно в количката" от писмата за
 * изоставена количка.
 *
 * ## Какво се счупи
 *
 * Платформата слага тези адреси в писмата през променливата `{$cart_url}`.
 * Преди прехвърлянето тя ги и обслужваше: хешът е шифрован с нейния ключ,
 * тя го разчита, влиза в профила на абоната и му връща количката.
 *
 * След насочването на домейна платформата обслужва само няколко пътя
 * (`/checkout`, `/admin`, `/api`, `/cdn`, `/sitemap.xml`); всичко друго е на
 * този worker. `/subscribers/*` не е сред тях, тоест бутонът във ВСЯКО писмо
 * за изоставена количка връщаше нашата 404 страница. Проверено на живо
 * 23.09.2026 с истинско писмо, и за `cart`, и за `subscriptions`.
 *
 * ## Какво правим
 *
 * Хешът не може да се разчете без ключа на платформата, значи чуждата количка
 * не може да се възстанови. Но човекът почти винаги отваря писмото на същото
 * устройство, откъдето е и количката ни в неговата бисквитка - затова го
 * пращаме на `/cart`, където си я намира.
 *
 * Полза покрай това: адресът носи и `cc_campaign`, а щом заявката минава през
 * нас, `server.ts` записва кампанията в cookie. Оттам нататък приписването
 * върви по пътя от `app/lib/campaign-attribution.ts` - тоест и поръчките от
 * изоставена количка се броят пак.
 *
 * 302, не 301: адресът е на сесия и не бива да се кешира никъде.
 */
export async function loader(_args: Route.LoaderArgs) {
  throw redirect('/cart', 302);
}
